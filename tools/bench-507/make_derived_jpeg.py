"""Derived JPEG variants for the 5.0.7 JPEG first-frame round (docs/perf/jpeg-first-frame-plan-5.0.7.md).

Takes real camera JPEGs from the read-only corpus and writes lossless (jpegtran) or re-encoded (Pillow)
variants into <corpus>/derived/ with its own manifest.csv (real_or_converted = "derived"). The source corpus
files are never modified; nothing is written into the repository.

    python tools/bench-507/make_derived_jpeg.py <bench-corpus> \
        --jpegtran <bench-codecs>/libjpeg-turbo/x/bin/jpegtran.exe
"""
import argparse, csv, os, struct, subprocess, sys
from PIL import Image

SOURCES = ["jpg-camera/pb_canon_eos_r6_mark_ii_03.jpg", "jpg-camera/pb_nikon_d850_04.jpg"]


def set_orientation(data: bytes, value: int) -> bytes:
    """Patch the EXIF IFD0 Orientation tag in place (no re-encode)."""
    buf = bytearray(data)
    i = 2
    while i + 4 < len(buf) and buf[i] == 0xFF:
        marker, length = buf[i + 1], struct.unpack(">H", buf[i + 2:i + 4])[0]
        if marker == 0xE1 and buf[i + 4:i + 10] == b"Exif\0\0":
            t = i + 10
            le = buf[t:t + 2] == b"II"
            u16 = (lambda o: struct.unpack("<H" if le else ">H", buf[o:o + 2])[0])
            u32 = (lambda o: struct.unpack("<I" if le else ">I", buf[o:o + 4])[0])
            ifd = t + u32(t + 4)
            for n in range(u16(ifd)):
                e = ifd + 2 + n * 12
                if u16(e) == 274:
                    buf[e + 8:e + 10] = struct.pack("<H" if le else ">H", value)
                    return bytes(buf)
            raise ValueError("no Orientation tag")
        if marker == 0xDA:
            break
        i += 2 + length
    raise ValueError("no EXIF APP1")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("corpus")
    ap.add_argument("--jpegtran", required=True)
    a = ap.parse_args()
    out = os.path.join(a.corpus, "derived")
    os.makedirs(out, exist_ok=True)
    rows = []

    def add(name, variant, src_rel):
        p = os.path.join(out, name)
        with Image.open(p) as im:
            w, h = im.size
        rows.append({"file": name, "format": "jpg", "variant": variant, "bytes": os.path.getsize(p), "width": w, "height": h,
                     "real_or_converted": "derived", "note": f"derived from {src_rel}"})

    for rel in SOURCES:
        src = os.path.join(a.corpus, rel)
        stem = os.path.splitext(os.path.basename(rel))[0]
        jt = lambda args, name: subprocess.run([a.jpegtran, *args, "-outfile", os.path.join(out, name), src], check=True)
        jt(["-copy", "all"], f"{stem}__orig.jpg"); add(f"{stem}__orig.jpg", "orig-thumb", rel)
        jt(["-copy", "all", "-progressive"], f"{stem}__prog.jpg"); add(f"{stem}__prog.jpg", "prog", rel)
        jt(["-copy", "all", "-restart", "1"], f"{stem}__rst.jpg"); add(f"{stem}__rst.jpg", "rst", rel)
        jt(["-copy", "none"], f"{stem}__noexif.jpg"); add(f"{stem}__noexif.jpg", "nothumb", rel)
        jt(["-copy", "all", "-grayscale"], f"{stem}__gray.jpg"); add(f"{stem}__gray.jpg", "gray", rel)
        jt(["-copy", "all", "-crop", "4001x2999+0+0"], f"{stem}__odd.jpg"); add(f"{stem}__odd.jpg", "odd", rel)
        with open(src, "rb") as f:
            data = f.read()
        with open(os.path.join(out, f"{stem}__exif6.jpg"), "wb") as f:
            f.write(set_orientation(data, 6))
        add(f"{stem}__exif6.jpg", "exif6", rel)
        with Image.open(src) as im:
            rgb = im.convert("RGB")
        rgb.convert("CMYK").save(os.path.join(out, f"{stem}__cmyk.jpg"), quality=90)
        add(f"{stem}__cmyk.jpg", "cmyk", rel)
        rgb.save(os.path.join(out, f"{stem}__444.jpg"), quality=92, subsampling=0)
        add(f"{stem}__444.jpg", "444", rel)
        rgb.save(os.path.join(out, f"{stem}__prog444.jpg"), quality=92, subsampling=0, progressive=True)
        add(f"{stem}__prog444.jpg", "prog444", rel)

    with open(os.path.join(out, "manifest.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(out, "DERIVED.txt"), "w") as f:
        f.write("DERIVED test files (not real-world originals): generated by tools/bench-507/make_derived_jpeg.py "
                "from the camera JPEGs listed in manifest.csv (note column).\n")
    print(f"{len(rows)} derived files in {out}")


if __name__ == "__main__":
    sys.exit(main())
